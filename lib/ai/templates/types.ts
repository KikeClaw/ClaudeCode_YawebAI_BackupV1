/** Content JSON the AI generates for template-based sites (copywriting only, no design). */
export interface TemplateContent {
  meta: {
    title: string        // "Business Name | Tagline" ≤60 chars
    description: string  // Meta description 150-160 chars
    keywords: string[]   // 4-6 SEO keywords
  }
  hero: {
    headline: string     // 6-10 words, compelling, benefit-focused
    subheadline: string  // 1-2 sentences elevator pitch
    cta_text: string     // Primary button text e.g. "Reservar cita"
  }
  about: {
    title: string        // Section heading e.g. "Quiénes somos"
    content: string      // 2-3 paragraphs separated by \n\n
    highlight?: string   // Optional: 1 key differentiator sentence
  }
  services: {
    title: string        // Section heading e.g. "Nuestros servicios"
    items: Array<{
      name: string
      description: string // 1-2 sentences
      price?: string      // "Desde X€" or empty string
      icon?: string       // Lucide icon name e.g. "scissors", "heart"
    }>
  }
  features?: {
    title: string        // e.g. "Por qué elegirnos"
    items: Array<{
      icon: string       // Lucide icon name
      title: string      // Short feature title
      text: string       // 1-2 sentence explanation
    }>
  }
  faq?: {
    title: string        // "Preguntas frecuentes"
    items: Array<{
      question: string
      answer: string     // 2-3 sentence specific answer
    }>
  }
  cta_section?: {
    headline: string
    subtext: string
    button_text: string
  }
  footer_tagline?: string // One-line brand statement
}

/** Data from Google Places API + generation options — NOT generated by AI. */
export interface TemplateMeta {
  businessName: string
  phone?: string
  phoneDisplay?: string
  whatsapp?: string      // raw number with country code
  address?: string
  heroImageUrl?: string
  aboutImageUrl?: string
  extraImageUrls?: string[]
  placeId?: string
  mapsApiKey?: string
  lang: 'es' | 'en' | 'de' | 'fr'
  year: number
  instagram?: string     // handle without @
  facebook?: string      // full URL
  tiktok?: string        // handle without @
}
